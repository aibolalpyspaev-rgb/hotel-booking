    public function run(): void
    {
        $amenities = Amenity::pluck('id', 'name');

        foreach ($this->hotels() as $hi => $data) {
            $rooms = $data['rooms'];
            unset($data['rooms']);

            $data['image_url'] = sprintf(self::IMG, $data['image_url']);
            $data['gallery'] = array_map(
                fn ($i) => sprintf(self::IMG, self::ROOM_PHOTOS[($hi * 3 + $i) % count(self::ROOM_PHOTOS)]),
                [0, 1, 2]
            );

            $hotel = Hotel::create($data);

            foreach ($rooms as $ri => [$name, $type, $price, $capacity, $beds, $area, $roomAmenities, $description]) {
                $room = $hotel->rooms()->create([
                    'name' => $name,
                    'type' => $type,
                    'price_per_night' => $price,
                    'capacity' => $capacity,
                    'beds' => $beds,
                    'area' => $area,
                    'description' => $description,
                    'image_url' => sprintf(self::IMG, self::ROOM_PHOTOS[($hi * 4 + $ri) % count(self::ROOM_PHOTOS)]),
                ]);

                $room->amenities()->sync(
                    collect($roomAmenities)->map(fn ($n) => $amenities[$n] ?? null)->filter()->values()->all()
                );
            }
        }
    }

